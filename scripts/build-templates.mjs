#!/usr/bin/env node
// Embeds prompts/**/*.md into TypeScript modules so no runtime needs file-system access
// (Expo Metro, browsers, and Deno all import plain strings). Output: src/generated/.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

import {
  DELIVERIES,
  GENERATED_DIR,
  loadPartials,
  loadPrompts,
  resolvePartials,
  ROOT,
} from './lib/prompt-source.mjs';

const HEADER = '// Generated by scripts/build-templates.mjs from prompts/. Do not edit.\n';

async function writeIfChanged(file, contents) {
  const existing = await readFile(file, 'utf8').catch(() => null);
  if (existing === contents) return false;
  await writeFile(file, contents);
  return true;
}

function bundleModule(prompts, partials) {
  const templates = Object.fromEntries(prompts.map((prompt) => [prompt.meta.id, prompt.templates]));
  const usedPartials = new Set();
  for (const prompt of prompts) {
    for (const name of resolvePartials(Object.values(prompt.templates), partials, prompt.meta.id)) {
      usedPartials.add(name);
    }
  }
  const bundlePartials = Object.fromEntries([...usedPartials].sort().map((name) => [name, partials[name]]));
  return (
    HEADER +
    "import type { TemplateBundle } from '../render/engine.js';\n\n" +
    `export const bundle: TemplateBundle = ${JSON.stringify(
      { templates, partials: bundlePartials },
      null,
      2,
    )};\n`
  );
}

function registryModule(prompts) {
  const metas = prompts.map((prompt) => prompt.meta);
  return (
    HEADER +
    "import type { PromptMeta } from '../registry/types.js';\n\n" +
    `export const promptRegistry: readonly PromptMeta[] = ${JSON.stringify(metas, null, 2)};\n`
  );
}

export async function generate({ quiet = false } = {}) {
  const [prompts, partials] = await Promise.all([loadPrompts(), loadPartials()]);
  await mkdir(GENERATED_DIR, { recursive: true });

  const outputs = {
    'registry.ts': registryModule(prompts),
  };
  for (const delivery of DELIVERIES) {
    outputs[`${delivery}.ts`] = bundleModule(
      prompts.filter((prompt) => prompt.meta.delivery === delivery),
      partials,
    );
  }

  const changed = [];
  for (const [file, contents] of Object.entries(outputs)) {
    if (await writeIfChanged(path.join(GENERATED_DIR, file), contents)) changed.push(file);
  }

  if (!quiet) {
    const counts = DELIVERIES.map(
      (delivery) => `${prompts.filter((prompt) => prompt.meta.delivery === delivery).length} ${delivery}`,
    ).join(', ');
    const where = path.relative(ROOT, GENERATED_DIR);
    console.log(`Generated ${where} (${counts})${changed.length ? `; updated ${changed.join(', ')}` : ''}`);
  }
  return { prompts, changed };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  generate().catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
