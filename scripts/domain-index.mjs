#!/usr/bin/env node
// Regenerates the prompt index inside each prompts/<domain>/README.md from meta.json files.
// Only the text between the markers is replaced; everything else in the README is hand-written.
// `--check` exits non-zero instead of writing when a README is out of date.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { loadPrompts, PROMPTS_DIR, ROOT } from './lib/prompt-source.mjs';

const START = '<!-- prompt-index:start (generated by `npm run docs:domain-index`; edit meta.json instead) -->';
const END = '<!-- prompt-index:end -->';

const cell = (value) => String(value).replace(/\|/g, '\\|').replace(/\n/g, ' ');

function indexTable(prompts) {
  const rows = prompts.map(({ slug, meta }) => {
    const surfaces = meta.usage.symthink.surfaces.length
      ? meta.usage.symthink.surfaces.map(cell).join('<br>')
      : '—';
    return `| [\`${meta.id}\`](#${slug}) | ${cell(meta.title)} | \`${meta.delivery}\` | \`${meta.usage.status}\` | ${surfaces} |`;
  });
  return [
    '| Id | Title | Delivery | Status | Symthink surface / API |',
    '|----|-------|----------|--------|------------------------|',
    ...rows,
  ].join('\n');
}

function promptDetails({ slug, meta }) {
  const files = meta.output === 'system_user' ? ['system.md', 'user.md'] : ['prompt.md'];
  const lines = [
    `### ${slug}`,
    '',
    meta.description,
    '',
    `- **Id:** \`${meta.id}\``,
    `- **Template:** ${files.map((file) => `[\`${file}\`](./${slug}/${file})`).join(', ')} · [\`meta.json\`](./${slug}/meta.json)`,
    `- **Output:** \`${meta.output}\`${meta.output === 'system_user' ? ' (returns `{ system, user }`)' : ' (returns one string)'}`,
    `- **Paste-back into Symthink:** ${meta.usage.pasteBack ? 'yes' : 'no'}`,
    `- **Wired in Symthink from this package:** ${meta.usage.symthink.wired ? 'yes' : 'not yet'}`,
  ];
  if (meta.usage.symthink.sourceFiles.length) {
    lines.push(`- **Symthink source:** ${meta.usage.symthink.sourceFiles.map((file) => `\`${file}\``).join(', ')}`);
  }
  if (meta.usage.symthink.docs) {
    lines.push(`- **Symthink docs:** \`${meta.usage.symthink.docs}\``);
  }
  if (meta.usage.notes) {
    lines.push(`- **Notes:** ${meta.usage.notes}`);
  }
  lines.push('');
  if (meta.variables.length) {
    lines.push('| Variable | Type | Required | Description |', '|----------|------|----------|-------------|');
    for (const variable of meta.variables) {
      lines.push(
        `| \`${variable.name}\` | \`${cell(variable.type)}\` | ${variable.required ? 'yes' : 'no'} | ${cell(variable.description)} |`,
      );
    }
  } else {
    lines.push('_No variables — the prompt is static._');
  }
  return lines.join('\n');
}

export function domainIndex(prompts) {
  return [START, '', indexTable(prompts), '', '## Prompt details', '', prompts.map(promptDetails).join('\n\n'), '', END].join(
    '\n',
  );
}

const PROVENANCE_START = '<!-- provenance:start (generated by `npm run docs:domain-index`; edit meta.json instead) -->';
const PROVENANCE_END = '<!-- provenance:end -->';

function provenanceTable(prompts) {
  const rows = prompts.map(({ domain, slug, meta }) => {
    const sources = meta.usage.symthink.sourceFiles.map((file) => `\`${cell(file)}\``).join('<br>') || '—';
    return `| [\`${meta.id}\`](prompts/${domain}/README.md#${slug}) | \`${meta.usage.status}\` | ${sources} |`;
  });
  return [
    PROVENANCE_START,
    '',
    '| Prompt | Status | Copied from (symthink-io) |',
    '|--------|--------|---------------------------|',
    ...rows,
    '',
    PROVENANCE_END,
  ].join('\n');
}

async function replaceBetween(file, startMarker, endMarker, body) {
  const relative = path.relative(ROOT, file);
  const contents = await readFile(file, 'utf8').catch(() => null);
  if (contents == null) {
    throw new Error(`${relative} is missing. Copy another README and keep the generated-section markers.`);
  }
  const start = contents.indexOf(startMarker);
  const end = contents.indexOf(endMarker);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`${relative} must contain the markers:\n${startMarker}\n${endMarker}`);
  }
  return { relative, contents, next: contents.slice(0, start) + body + contents.slice(end + endMarker.length) };
}

async function main() {
  const check = process.argv.includes('--check');
  const prompts = await loadPrompts();
  const domains = [...new Set(prompts.map((prompt) => prompt.domain))];
  const stale = [];

  const targets = [
    ...domains.map((domain) => ({
      file: path.join(PROMPTS_DIR, domain, 'README.md'),
      start: START,
      end: END,
      body: domainIndex(prompts.filter((prompt) => prompt.domain === domain)),
    })),
    { file: path.join(ROOT, 'README.md'), start: PROVENANCE_START, end: PROVENANCE_END, body: provenanceTable(prompts) },
  ];

  for (const target of targets) {
    const { relative, contents: readme, next } = await replaceBetween(target.file, target.start, target.end, target.body);
    const readmePath = target.file;
    if (next === readme) continue;
    if (check) {
      stale.push(relative);
    } else {
      await writeFile(readmePath, next);
      console.log(`Updated ${relative}`);
    }
  }

  if (stale.length) {
    console.error(`Out of date: ${stale.join(', ')}\nRun \`npm run docs:domain-index\` and commit the result.`);
    process.exit(1);
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
